WITH USER_ORDER_METRICS AS (
    SELECT *
    FROM {{ ref('int_user_order_metrics') }}
),

REORDER_RATE_PRIOR AS (
    SELECT 
        MEDIAN(ORDER_COUNT) AS M,
        AVG(REORDER_RATE) AS C
    FROM 
        USER_ORDER_METRICS
)

SELECT 
    USER_ID,
    ORDER_COUNT,
    AVG_ITEMS_PER_ORDER,
    UNIQUE_PRODUCTS,
    ROUND(REORDER_RATE, 2) AS REORDER_RATE,
    ROUND(
        (ORDER_COUNT/(ORDER_COUNT + M)) * REORDER_RATE +
        (M/(M+ORDER_COUNT)) * C,
        2 
    ) AS WEIGHTED_REORDER_RATE
FROM    
    USER_ORDER_METRICS
CROSS JOIN 
    REORDER_RATE_PRIOR
